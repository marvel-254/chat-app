import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { PGlite } from '@electric-sql/pglite';

const db = new PGlite();
const read = (path) => readFileSync(new URL(path, import.meta.url), 'utf8');
const run = (sql) => db.exec(sql);
const rows = async (sql) => (await db.query(sql)).rows;
const id = (n) => `10000000-0000-4000-8000-${String(n).padStart(12, '0')}`;
const a = id(1), b = id(2), c = id(3), dm = id(4), device = id(5), device2 = id(6);
const call = (n) => id(100 + n);
const assume = async (role, uid = '') => run(`reset role; set role ${role}; select set_config('request.jwt.claim.sub','${uid}',false);`);
const start = (n) => rows(`select * from start_bro_call('${call(n)}','${dm}','${b}',false)`);
const advance = (n, action) => rows(`select * from advance_bro_call('${call(n)}','${action}')`);
const status = async (n) => (await rows(`select status from call_sessions where id='${call(n)}'`))[0]?.status;

try {
  await run(read('./bro_fixture.sql'));
  await run(read('../migrations/20261120120000_call_sessions.sql'));
  await run(read('../migrations/20261120130000_push_delivery.sql'));
  await run(read('../migrations/20261120140001_legacy_message_format.sql'));
  await run(`insert into auth.users values ('${a}'),('${b}'),('${c}');
    insert into conversations values ('${dm}');
    insert into conversation_participants values ('${dm}','${a}'),('${dm}','${b}');`);
  await assume('authenticated', c);
  await assert.rejects(start(1), /Call unavailable/);
  await assert.rejects(rows('select * from claim_bro_push()'), /permission denied/);
  await assume('authenticated', b);
  await run(`select register_bro_push('${b}','${device}','recipient-token-placeholder-1234','android');
    select register_bro_push('${b}','${device2}','recipient-token-placeholder-5678','web');`);
  await assume('authenticated', a);
  assert.equal((await start(1))[0].status, 'ringing');
  assert.equal((await start(1))[0].id, call(1));
  await assert.rejects(advance(1, 'accept'), /no longer ringing/);
  await assert.rejects(run(`update call_sessions set status='completed'`), /permission denied/);
  await assume('authenticated', c);
  assert.equal(await status(1), undefined);
  await assert.rejects(advance(1, 'reject'), /Call unavailable/);
  await assert.rejects(run(`select signal_bro_call('${call(1)}','ice','{}'::jsonb)`), /Signal unavailable/);
  assert.equal((await rows('select token from bro_push_devices')).length, 0);
  await assert.rejects(run(`select register_bro_push('${b}','${device}','recipient-token-placeholder-1234','android')`), /42501|exception/i);
  await assert.rejects(run(`select register_bro_push('${c}','${device}','recipient-token-placeholder-1234','android')`), /duplicate key/);
  await assume('service_role');
  assert.equal((await rows('select * from claim_bro_push()')).length, 2);
  assert.equal((await rows('select * from claim_bro_push()')).length, 0);
  await assume('authenticated', b);
  assert.equal((await advance(1, 'accept'))[0].status, 'accepted');
  await assert.rejects(advance(1, 'accept'), /no longer ringing/);
  await assert.rejects(run(`select signal_bro_call('${call(1)}','offer','{}'::jsonb)`), /Signal unavailable/);
  await assume('authenticated', a);
  await run(`select signal_bro_call('${call(1)}','offer','{}'::jsonb)`);
  const connected = (await advance(1, 'connected'))[0].connected_at;
  assert.ok(connected);
  assert.deepEqual((await advance(1, 'heartbeat'))[0].connected_at, connected);
  assert.equal((await advance(1, 'end'))[0].status, 'completed');
  assert.equal((await advance(1, 'fail'))[0].status, 'completed');
  await run(`select hide_bro_calls('${call(1)}')`);
  assert.equal(await status(1), undefined);
  await assume('authenticated', b);
  assert.equal(await status(1), 'completed');
  await assume('authenticated', a);
  await start(2);
  assert.equal((await advance(2, 'end'))[0].status, 'cancelled');
  await start(3);
  await assume('authenticated', b);
  assert.equal((await advance(3, 'reject'))[0].status, 'rejected');
  await assume('authenticated', a);
  await start(4);
  await assume('postgres');
  await run(`update call_sessions set expires_at=now()-interval '1 second' where id='${call(4)}'`);
  await assume('authenticated', b);
  assert.equal((await advance(4, 'accept'))[0].status, 'missed');
  assert.equal((await advance(4, 'refresh'))[0].status, 'missed');
  await assume('authenticated', a);
  await start(5);
  assert.equal((await advance(5, 'fail'))[0].status, 'failed');
  await assume('service_role');
  const jobs = await rows('select * from claim_bro_push()');
  assert.equal(jobs.length, 2);
  assert.ok(jobs.every(job => job.kind === 'missed_call' && job.source_id === call(4)));
  assert.equal((await rows('select * from claim_bro_push()')).length, 0);
  await assume('authenticated', b);
  await run(`select hide_bro_calls(null); insert into bro_notification_preferences(user_id,messages) values ('${b}',false);`);
  await assume('postgres');
  await run(`insert into messages(id,conversation_id,sender_id,content) values ('${id(90)}','${dm}','${a}','private message body');`);
  assert.equal((await rows(`select content_format from messages where id='${id(90)}'`))[0].content_format, 'legacy_unversioned');
  await assert.rejects(run(`update messages set content_format='legacy_plaintext'`), /independently/);
  assert.ok(!(await rows('select row_to_json(e)::text payload from bro_push_events e')).some(row => row.payload.includes('private message body')));
  await assume('service_role');
  assert.equal((await rows('select * from claim_bro_push()')).length, 0);
  await assume('authenticated', b);
  await run(`update bro_notification_preferences set messages=true;`);
  await assume('service_role');
  assert.equal((await rows('select * from claim_bro_push()')).length, 2);
  await assume('authenticated', a);
  for (let n = 0; n < 10; n++) assert.equal((await rows('select claim_bro_turn() value'))[0].value, true);
  assert.equal((await rows('select claim_bro_turn() value'))[0].value, false);
  console.log('Call transitions, call history RLS, token ownership, queue claims, missed-call deduplication and TURN quotas passed.');
} catch (error) {
  console.error(error.message, error.code ?? '', error.detail ?? '', error.where ?? '', error.query?.slice(0, 100));
  process.exitCode = 1;
} finally {
  await db.close();
}
